type Options = { values: Record<string, string>; links: string[]; yes: boolean; json: boolean; preview: boolean; help: boolean };
export function parseMemoryMaintenanceOptions(command: string, args: string[]): Options {
  const opts: Options = { values: {}, links: [], yes: false, json: false, preview: false, help: false };
  const valueFlags = command === 'plan'
    ? ['--owner', '--target', '--op', '--rationale', '--reviewer', '--out', '--input', '--recommendation', '--placement', '--category', '--replacements', '--related', '--link', '--retirement-basis']
    : command === 'verify' ? ['--plan'] : ['--plan', '--confirm'];
  valueFlags.push('--scope');
  const booleanFlags = ['--json', '--help', '-h', ...(command === 'verify' ? [] : ['--preview']), ...(['apply', 'restore'].includes(command) ? ['--yes'] : [])];
  const seen = new Set<string>();
  for (let index = 0; index < args.length; index++) {
    const equal = args[index].indexOf('=');
    const flag = equal < 0 ? args[index] : args[index].slice(0, equal);
    const inline = equal < 0 ? undefined : args[index].slice(equal + 1);
    if (!valueFlags.includes(flag) && !booleanFlags.includes(flag)) throw new Error(`Unknown memory ${command} argument: ${args[index]}`);
    const key = flag === '-h' ? '--help' : flag;
    if (seen.has(key) && flag !== '--link') throw new Error(`Duplicate memory ${command} option: ${flag}`);
    seen.add(key);
    if (booleanFlags.includes(flag)) {
      if (inline !== undefined) throw new Error(`${flag} takes no value`);
      if (key === '--help') opts.help = true;
      else if (flag === '--yes') opts.yes = true;
      else if (flag === '--json') opts.json = true;
      else opts.preview = true;
    } else {
      const value = inline ?? args[++index];
      if (!value || value.startsWith('-')) throw new Error(`${flag} requires a value`);
      if (flag === '--link') opts.links.push(value);
      else opts.values[flag.slice(2)] = value;
    }
  }
  if (opts.help) return opts;
  if (opts.values.scope && opts.values.scope !== 'project') throw new Error('Executable maintenance supports --scope project only; use audit --scope global for global inventory');
  if (opts.yes && opts.values.confirm) throw new Error('--yes and --confirm are mutually exclusive');
  if (command === 'plan') {
    if (opts.values.recommendation) {
      if (!opts.values.reviewer) throw new Error('--reviewer is required for recommendation review');
      if (Object.keys(opts.values).some(key => !['recommendation', 'reviewer', 'out', 'category', 'replacements', 'scope'].includes(key))) throw new Error('--recommendation cannot be combined with operation or exact-plan flags');
    } else if (opts.values.input) {
      if (Object.keys(opts.values).some(key => !['input', 'out', 'scope'].includes(key)) || opts.links.length) throw new Error('--input cannot be combined with operation flags');
    } else {
      for (const required of ['owner', 'target', 'op', 'rationale', 'reviewer']) if (!opts.values[required]) throw new Error(`--${required} is required`);
    }
    if (opts.preview && opts.values.out) throw new Error('--preview and --out are mutually exclusive');
    if (!opts.preview && !opts.values.out) throw new Error('--out is required unless --preview is selected');
  } else {
    if (!opts.values.plan) throw new Error('--plan is required');
    if (opts.preview && (opts.yes || opts.values.confirm)) throw new Error('--preview cannot be combined with confirmation');
  }
  return opts;
}

export async function createMaintenanceOwners(root: string): Promise<MaintenanceOwner[]> {
  const [{ LineMaintenanceOwner }, { CanonicalMaintenanceOwner }, { ArtifactMaintenanceOwner }] = await Promise.all([
    import('./line-maintenance.js'), import('./canonical-maintenance.js'), import('../artifacts/memory-maintenance.js'),
  ]);
  const artifact = new ArtifactMaintenanceOwner(root);
  // These resident owners do not yet publish an owner-native indexed projection.
  // Their default verifier explicitly refuses resident removal; an unrelated
  // artifact copy must not turn that unsupported operation into a valid plan.
  return [new LineMaintenanceOwner(root), new CanonicalMaintenanceOwner(root), artifact];
}

export async function runMemoryMaintenanceCli(command: string, args: string[], dependencies: {
  root?: string; owners?: MaintenanceOwner[]; isTTY?: boolean; confirm?: (digest: string) => Promise<string>;
} = {}): Promise<number | void> {
  const opts = memoryUsage(() => parseMemoryMaintenanceOptions(command, args));
  if (opts.help) { console.log(MEMORY_MAINTENANCE_USAGE); return; }
  const root = dependencies.root ?? process.cwd();
  const owners = dependencies.owners ?? await createMaintenanceOwners(root);
  const readJson = (path: string): unknown => memoryUsage(() => JSON.parse(readFileSync(maintenancePath(root, path), 'utf8')));
  let recommendationRelated: string[] | undefined;
  let recommendationUncertainty: string | undefined;
  if (command === 'plan' && opts.values.recommendation) {
    const report = memoryUsage(() => MemoryRecommendationsSchema.parse(readJson(opts.values.recommendation)));
    if (report.workspace !== root || report.candidates.length !== 1) throw new Error('Review input requires one candidate from this workspace');
    const candidate = report.candidates[0];
    if (candidate.status !== 'advisory' || candidate.blockedReasons.length) throw new Error('Blocked, rejected or conflicting recommendations cannot become plans');
    if (candidate.kind === 'conflict') throw new Error('Conflicts require explicit source resolution');
    if (['merge', 'supersede'].includes(candidate.kind) && !opts.values.replacements) throw new Error('Lineage recommendations require explicit owner review with --replacements');
    const target = candidate.target;
    if (target.scope !== 'project') throw new Error('Executable recommendation review requires a project-owned source');
    const file = maintenancePath(root, target.sourcePath);
    if (sha256(readFileSync(file, 'utf8')) !== candidate.sourceDigest) throw new Error('Stale recommendation source digest; rerun recommend');
    const owner = owners.find(value => value.name === target.authority.owner);
    if (!owner) throw new Error('Recommendation source has no executable maintenance owner');
    // Audit fingerprints whole files. The owner binds its native body/revision and
    // snapshot only after the reviewer selects this exact unchanged source.
    const record = (await owner.records()).find(value => value.sourcePath === target.sourcePath);
    if (!record) throw new Error('Recommendation source is not an individual owner target; review an owner handle explicitly');
    if (candidate.kind === 'merge') {
      if (candidate.related.length !== candidate.relatedTargets.length) throw new Error('Merge review requires every related source revision');
      const records = await owner.records();
      recommendationRelated = candidate.relatedTargets.map(binding => {
        const related = binding.record;
        if (related.scope !== target.scope || related.authority.owner !== owner.name) throw new Error('Merge recommendation cannot cross scope or owners');
        if (sha256(readFileSync(maintenancePath(root, related.sourcePath), 'utf8')) !== binding.sourceDigest) throw new Error('Stale related recommendation source digest');
        const input = records.find(value => value.sourcePath === related.sourcePath);
        if (!input) throw new Error('Related recommendation source is not an individual owner target');
        return input.id;
      });
    }
    recommendationUncertainty = candidate.uncertainty.join('; ');
    opts.values.owner = owner.name;
    opts.values.target = record.id;
    opts.values.op = candidate.kind;
    opts.values.rationale = candidate.rationale + (candidate.residentJustification ? `; Resident justification: ${JSON.stringify(candidate.residentJustification)}` : '');
    if (candidate.retrievalImpact.proposedPlacement) opts.values.placement = candidate.retrievalImpact.proposedPlacement;
    opts.values.category ??= candidate.retrievalImpact.category ?? '';
    opts.values['retirement-basis'] = 'review';
  }
  let plan: MaintenancePlan;
  if (command === 'plan' && !opts.values.input) {
    const owner = owners.find(value => value.name === opts.values.owner);
    if (!owner) throw new Error(`Unavailable maintenance owner: ${opts.values.owner}`);
    const records = await owner.records();
    const aliases = indexMemoryAliases(records);
    const record = aliases.get(opts.values.target);
    if (!record) throw new Error('Maintenance target is missing');
    const op = memoryUsage(() => MaintenanceOpSchema.parse(opts.values.op));
    const lifecycle = op === 'retire' ? 'retired' : ['merge', 'split', 'supersede'].includes(op) ? 'superseded' : op === 'restore' ? 'active' : record.lifecycle;
    const placement = opts.values.placement ? memoryUsage(() => MemoryPlacementSchema.parse(opts.values.placement)) : record.placement;
    const relatedInput = recommendationRelated ?? (opts.values.related ? readJson(opts.values.related) : []);
    if (!Array.isArray(relatedInput) || relatedInput.some(value => typeof value !== 'string')) throw new Error('--related requires a JSON array of existing owner handles');
    const related = relatedInput.map(handle => {
      const input = aliases.get(handle);
      if (!input) throw new Error(`Related target is missing: ${handle}`);
      return { id: input.id, digest: input.digest, version: input.version };
    });
    plan = { schemaVersion: 'aiwg.maintenance-plan.v1', operations: [{
      op, target: { id: record.id, digest: record.digest, version: record.version },
      from: { placement: record.placement, lifecycle: record.lifecycle }, to: { placement, lifecycle },
      scope: record.scope, rationale: opts.values.rationale, uncertainty: recommendationUncertainty ?? 'Static review; live session loading is unobserved',
      impactedLinks: opts.links, sessionEffect: 'next-session', precondition: { digest: record.digest, version: record.version },
      owner: { name: owner.name, handle: record.aliases[0] ?? record.id, snapshot: await owner.snapshot() },
      review: { reviewer: opts.values.reviewer, retirementBasis: (opts.values['retirement-basis'] ?? 'age') as 'age' | 'review' },
      ...(related.length ? { related } : {}), ...(opts.values.category ? { category: opts.values.category } : {}),
      ...(opts.values.replacements ? { replacements: readJson(opts.values.replacements) as NonNullable<MaintenancePlan['operations'][number]['replacements']> } : {}),
    }] };
  } else plan = readJson(opts.values.input ?? opts.values.plan) as MaintenancePlan;
  plan = memoryUsage(() => MaintenancePlanSchema.parse(plan));
  if (command === 'verify') {
    const report = await verifyMaintenancePlan(plan, owners);
    const review = maintenanceReview(plan, root);
    console.log(opts.json ? JSON.stringify({ ...report, review }, null, 2) : `${report.planDigest}: ${report.findings.length ? report.findings.join('; ') : 'verified recorded owner end states, history and required retrieval'}\n${formatMaintenanceReview(review)}`);
    return report.findings.length ? 1 : 0;
  }
  if (command === 'restore' && plan.operations?.some(op => op.op !== 'restore')) throw new Error('memory restore requires a plan containing only restore operations');
  if (command === 'plan' || opts.preview) {
    plan = await previewMaintenancePlan(plan, owners);
    const digest = maintenancePlanDigest(plan);
    const review = maintenanceReview(plan, root);
    if (command === 'plan' && !opts.preview) {
      const path = maintenancePath(root, opts.values.out);
      if (existsSync(path)) throw new Error('Plan output exists; choose a new file to preserve the reviewed preview');
      console.error(opts.json ? JSON.stringify({ event: 'maintenance-review', planDigest: digest, review }) : formatMaintenanceReview(review));
      writeFileSync(path, `${JSON.stringify(plan, null, 2)}\n`, { flag: 'wx', mode: 0o600 });
    }
    console.log(opts.json ? JSON.stringify({ planDigest: digest, plan, review }, null, 2) : `${digest}\n${formatMaintenanceReview(review)}`);
    return;
  }
  const digest = maintenancePlanDigest(plan);
  const review = maintenanceReview(plan, root);
  console.error(opts.json ? JSON.stringify({ event: 'maintenance-review', planDigest: digest, review }) : formatMaintenanceReview(review));
  let confirmed = opts.values.confirm;
  if (opts.yes) confirmed = digest;
  if (!confirmed) {
    if (!(dependencies.isTTY ?? (process.stdin.isTTY && process.stdout.isTTY)) || opts.json) memoryUsage(() => { throw new Error('Noninteractive apply requires --yes or --confirm <exact-plan-digest>'); });
    console.log(JSON.stringify(plan, null, 2));
    if (dependencies.confirm) confirmed = await dependencies.confirm(digest);
    else {
      const readline = createInterface({ input: process.stdin, output: process.stdout });
      try { confirmed = await readline.question(`Type the exact plan digest to apply ${digest}: `); }
      finally { readline.close(); }
    }
  }
  const receipt = await applyMaintenancePlan(plan, { root, owners, confirmedDigest: confirmed! });
  console.log(opts.json ? JSON.stringify(receipt, null, 2) : `${receipt.planDigest}: ${receipt.ownerReceipts.length} owner operation(s) completed; next-session effect`);
}


/** Review envelope shared by human output, JSON previews and pre-mutation events. */
export function maintenanceReview(plan: MaintenancePlan, root: string) {
  const scopes = [...new Set(plan.operations.map(operation => operation.scope))];
  return {
    targeting: { workspace: root, scope: scopes.join(', '), global: scopes.includes('global'), globalMutationSupported: false },
    diff: plan.operations.map(operation => ({ ...operation })),
    ownerReview: plan.operations.map(operation => ({ owner: operation.owner, review: operation.review,
      requirement: 'Exact owner snapshot and reviewer required; confirmation never bypasses owner validation' })),
    limitations: ['Static durable state only; live native/session loading is unobserved',
      'Changes take effect next-session; running sessions are unchanged',
      'Provider-native files require regeneration by their existing owner',
      'Line-memory and compound-memory resident removal requires an owner-native indexed projection and is currently unsupported'],
  };
}
function formatMaintenanceReview(review: ReturnType<typeof maintenanceReview>): string {
  return [`Target: ${review.targeting.scope} ${review.targeting.workspace}; global mutation unsupported`,
    ...review.diff.flatMap(operation => [
      `${operation.op} ${operation.owner?.name}:${operation.owner?.handle}: ${operation.from.placement}/${operation.from.lifecycle} -> ${operation.to.placement}/${operation.to.lifecycle}${operation.category ? `; category -> ${operation.category}` : ''}; ${operation.scope}; ${operation.sessionEffect}; reviewer ${operation.review?.reviewer}; rationale: ${operation.rationale}`,
      `  revision ${operation.target.version}; digest ${operation.target.digest}; owner snapshot ${operation.owner?.snapshot}; retirement basis ${operation.review?.retirementBasis}`,
      `  uncertainty: ${operation.uncertainty}; links: ${JSON.stringify(operation.impactedLinks)}`,
      ...(operation.related?.length ? [`  related revisions: ${JSON.stringify(operation.related)}`] : []),
      ...(operation.replacements?.length ? [`  replacements: ${JSON.stringify(operation.replacements)}`] : []),
    ]),
    'Owner review: exact snapshot, source revision and reviewer required.',
    ...review.limitations].join('\n');
}
