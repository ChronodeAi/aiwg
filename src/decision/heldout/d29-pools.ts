/** Disjoint train/test wording pools for the D29 v7 held-out study.
 *
 * Every wording family below ships two disjoint pools: TRAIN (tuning and
 * calibration rows only) and TEST (final-test rows only). The v7 renderer
 * selects its pool by split, so no test-pool wording ever appears in a
 * tuning or calibration row. The primary v3 passage baseline is built from
 * the TRAIN pools only; TEST wording (novel verbs, qualifiers, criterion
 * periphrases, coreference renderings) is parser-unseen by construction.
 *
 * Benign operator notes reuse their own pool's injection vocabulary and
 * share sentence frames and length distributions with that pool's
 * injections, so no lexicon, length or framing shortcut separates injected
 * from benign rows within or across pools.
 */
import { readFileSync } from 'node:fs';
import { sha256 } from '../compile-cache/identity.js';
export interface D29WordPool {
  /** Paraphrase frame verb: train `The <noun> recorded for Module M is V`, test `logged`. */
  paraphraseVerb: string;
  /** Claim/fact verbs per attribute: train verbs parse with the v2/v3 passage rules, test verbs do not. */
  verbs: Record<string, { direct: string; negated: string; movedOut: string; movedIn: string; exclusiveOnly: string; exclusiveLimited: string }>;
  scoped: readonly string[];
  temporal: readonly string[];
  tentative: readonly string[];
  /** Criterion evidence phrasing per mode; functions keep module/criterion placement explicit. */
  criterion: Record<string, (module: string, name: string, extra?: string) => string>;
  roles: readonly string[];
  tasks: readonly string[];
  timings: readonly string[];
  injections: readonly string[];
  framing: { citation: string; criterion: string };
}

