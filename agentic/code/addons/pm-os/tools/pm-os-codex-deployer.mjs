export class PmosCodexDeploymentError extends Error {}

function fail(message) {
  throw new PmosCodexDeploymentError(message);
}

function loadJson(filename) {
  try {
    return JSON.parse(fs.readFileSync(filename, 'utf8'));
  } catch (error) {
    fail(`cannot read valid JSON from ${filename}: ${error.message}`);
  }
}

function lstatIfExists(filename) {
  try {
    return fs.lstatSync(filename);
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
}

export function parseCliArgs(argv) {
  const cfg = {
    source: null,
    target: null,
    projectRoot: null,
    aiwgRoot: null,
    mode: 'all',
    dryRun: false,
    force: false,
    copyAll: false
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (
      arg === '--source' ||
      arg === '--target' ||
      arg === '--project-root' ||
      arg === '--aiwg-root' ||
      arg === '--mode'
    ) {
      if (!argv[i + 1]) fail(`${arg} requires a value`);
      const key = {
        '--source': 'source',
        '--target': 'target',
        '--project-root': 'projectRoot',
        '--aiwg-root': 'aiwgRoot',
        '--mode': 'mode'
      }[arg];
      cfg[key] = argv[++i];
    } else if (arg === '--dry-run') {
      cfg.dryRun = true;
    } else if (arg === '--force') {
      cfg.force = true;
    } else if (arg === '--copy-all' || arg === '--copy-standard-skills') {
      cfg.copyAll = true;
    } else {
      fail(`unsupported argument: ${arg}`);
    }
  }
  if (!cfg.source) fail('--source is required');
  return cfg;
}

function assertNoSymlinkComponents(root, target) {
  const relative = path.relative(root, target);
  if (!relative || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    if (relative) fail(`target escapes resolved project root: ${target}`);
    return;
  }
  let cursor = root;
  for (const part of relative.split(path.sep)) {
    cursor = path.join(cursor, part);
    const stat = lstatIfExists(cursor);
    if (stat?.isSymbolicLink()) {
      fail(`refusing symlinked deployment component: ${cursor}`);
    }
  }
}

function resolveExistingDirectory(requested, label) {
  const resolved = path.resolve(requested);
  const stat = lstatIfExists(resolved);
  if (!stat || !stat.isDirectory() || stat.isSymbolicLink()) {
    fail(`${label} must be an existing non-symlink directory: ${resolved}`);
  }
  const real = fs.realpathSync(resolved);
  if (real !== resolved) fail(`${label} must resolve without a symlink: ${resolved}`);
  if (path.dirname(resolved) === resolved) fail(`${label} cannot be a filesystem root: ${resolved}`);
  return resolved;
}

function validatePromotedAiwgRoot(requested) {
  const configured = requested || process.env.AIWG_ROOT;
  if (!configured) {
    fail('promoted PMOS source requires --aiwg-root or AIWG_ROOT');
  }
  const aiwgRoot = resolveExistingDirectory(configured, 'AIWG root');
  const packageFile = path.join(aiwgRoot, 'package.json');
  const cliFile = path.join(aiwgRoot, 'bin', 'aiwg.mjs');
  const frameworksDir = path.join(aiwgRoot, 'agentic', 'code', 'frameworks');
  const addonsDir = path.join(aiwgRoot, 'agentic', 'code', 'addons');

  for (const [candidate, label, type] of [
    [packageFile, 'AIWG package manifest', 'file'],
    [cliFile, 'AIWG CLI entrypoint', 'file'],
    [frameworksDir, 'AIWG frameworks directory', 'directory'],
    [addonsDir, 'AIWG addons directory', 'directory']
  ]) {
    assertNoSymlinkComponents(aiwgRoot, candidate);
    const stat = lstatIfExists(candidate);
    const valid = type === 'file' ? stat?.isFile() : stat?.isDirectory();
    if (!valid || stat.isSymbolicLink()) fail(`missing or unsafe ${label}: ${candidate}`);
  }

  const packageManifest = loadJson(packageFile);
  if (packageManifest.name !== 'aiwg' || packageManifest.bin?.aiwg !== 'bin/aiwg.mjs') {
    fail(`AIWG root package identity is invalid: ${packageFile}`);
  }
  return aiwgRoot;
}

function projectLocalRootFor(addonRoot) {
  const addonsDir = path.dirname(addonRoot);
  const aiwgDir = path.dirname(addonsDir);
  if (
    path.basename(addonRoot) !== 'pm-os' ||
    path.basename(addonsDir) !== 'addons' ||
    path.basename(aiwgDir) !== '.aiwg'
  ) return null;
  return path.dirname(aiwgDir);
}

export function resolveProjectLayout(source, contracts = {}) {
  const requested = path.resolve(source);
  const requestedStat = lstatIfExists(requested);
  if (!requestedStat || !requestedStat.isDirectory() || requestedStat.isSymbolicLink()) {
    fail(`addon source is not a directory: ${requested}`);
  }
  const addonRoot = fs.realpathSync(requested);
  if (addonRoot !== requested) fail(`addon source must resolve without a symlink: ${requested}`);

  const derivedProjectRoot = projectLocalRootFor(addonRoot);
  let projectRoot;
  let aiwgRoot = null;
  let sourceKind;
  if (derivedProjectRoot) {
    projectRoot = resolveExistingDirectory(derivedProjectRoot, 'project root');
    if (contracts.projectRoot) {
      const signaledProjectRoot = resolveExistingDirectory(contracts.projectRoot, 'signaled project root');
      if (signaledProjectRoot !== projectRoot) {
        fail(`project-local source does not belong to signaled project root: ${signaledProjectRoot}`);
      }
    }
    sourceKind = 'project-local';
  } else {
    aiwgRoot = validatePromotedAiwgRoot(contracts.aiwgRoot);
    const expected = path.join(aiwgRoot, 'agentic', 'code', 'addons', 'pm-os');
    assertNoSymlinkComponents(aiwgRoot, expected);
    const expectedStat = lstatIfExists(expected);
    if (!expectedStat || !expectedStat.isDirectory() || expectedStat.isSymbolicLink()) {
      fail(`missing or unsafe promoted PMOS addon: ${expected}`);
    }
    if (fs.realpathSync(expected) !== expected || addonRoot !== expected) {
      fail(`source is not the PMOS addon owned by the validated AIWG root: ${addonRoot}`);
    }
    if (!contracts.projectRoot) {
      fail('promoted PMOS source requires --project-root');
    }
    projectRoot = resolveExistingDirectory(contracts.projectRoot, 'signaled project root');
    sourceKind = 'promoted';
  }

  const manifest = loadJson(path.join(addonRoot, 'manifest.json'));
  if (manifest.id !== 'pm-os' || manifest.type !== 'addon' || manifest.manifestVersion !== '1') {
    fail('source manifest is not the strict PMOS addon manifest');
  }
  return { addonRoot, projectRoot, manifest, sourceKind, aiwgRoot };
}

function safeArtifactPath(addonRoot, relative, pattern, label) {
  if (typeof relative !== 'string' || !pattern.test(relative)) {
    fail(`unsafe ${label} path: ${String(relative)}`);
  }
  const resolved = path.resolve(addonRoot, relative);
  const prefix = `${addonRoot}${path.sep}`;
  if (!resolved.startsWith(prefix)) fail(`${label} escapes addon root: ${relative}`);
  if (!fs.existsSync(resolved) || !fs.statSync(resolved).isFile()) {
    fail(`missing ${label}: ${relative}`);
  }
  return resolved;
}

function validateSource(layout) {
  const { addonRoot, manifest } = layout;
  const config = manifest.addonConfig;
  if (!config || !Array.isArray(config.skills) || !Array.isArray(config.agents) || !Array.isArray(config.commands)) {
    fail('manifest addonConfig must enumerate skills, agents, and commands');
  }
  if (config.skills.length !== EXPECTED_PACKAGED_SKILLS || !config.skills.includes(QUICKREF)) {
    fail(`expected ${EXPECTED_PACKAGED_SKILLS} packaged skills including ${QUICKREF}`);
  }
  if (config.agents.length !== EXPECTED_AGENTS) fail(`expected ${EXPECTED_AGENTS} manifest agents`);
  if (config.commands.length !== EXPECTED_COMMANDS) fail(`expected ${EXPECTED_COMMANDS} manifest commands`);

  const skillDirs = fs.readdirSync(path.join(addonRoot, 'skills'), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(addonRoot, 'skills', entry.name, 'SKILL.md')))
    .map((entry) => entry.name);
  if (skillDirs.length !== EXPECTED_PACKAGED_SKILLS || !skillDirs.includes(QUICKREF)) {
    fail(`expected ${EXPECTED_PACKAGED_SKILLS} packaged SKILL.md directories, found ${skillDirs.length}`);
  }

  const skills = loadJson(path.join(addonRoot, 'registry', 'skills.json'));
  const activeSkills = Array.isArray(skills) ? skills.filter((item) => item.status === 'active') : [];
  if (activeSkills.length !== EXPECTED_SOURCE_SKILLS) {
    fail(`expected ${EXPECTED_SOURCE_SKILLS} active source skills, found ${activeSkills.length}`);
  }
  const activePaths = new Set();
  for (const skill of activeSkills) {
    const relative = skill.path;
    safeArtifactPath(addonRoot, relative, /^skills\/[a-z0-9][a-z0-9-]*\/SKILL\.md$/, 'registered skill');
    activePaths.add(relative);
  }
  if (activePaths.size !== EXPECTED_SOURCE_SKILLS) fail('active skill paths are not unique');

  const commands = loadJson(path.join(addonRoot, 'registry', 'commands.json'));
  if (!Array.isArray(commands) || commands.length !== EXPECTED_COMMANDS) {
    fail(`expected ${EXPECTED_COMMANDS} command records`);
  }
  const core = commands.filter((item) => item.type === 'core').length;
  const workflows = commands.filter((item) => item.type === 'workflow').length;
  if (core !== EXPECTED_CORE_COMMANDS || workflows !== EXPECTED_WORKFLOWS) {
    fail(`expected ${EXPECTED_CORE_COMMANDS} core and ${EXPECTED_WORKFLOWS} workflow command records`);
  }
  if (!commands.some((item) => item.slug === 'skill-browser' && item.type === 'core')) {
    fail('skill-browser is missing from the core command surface');
  }
  for (const command of commands) {
    safeArtifactPath(addonRoot, command.canonical_file, /^skills\/[a-z0-9][a-z0-9-]*\/SKILL\.md$/, 'command skill');
    if (!activePaths.has(command.canonical_file)) {
      fail(`command references a non-source skill: ${command.canonical_file}`);
    }
  }

  const commandDir = path.join(addonRoot, 'commands');
  const commandFiles = fs.readdirSync(commandDir)
    .filter((name) => name.startsWith('pm-os-') && name.endsWith('.md'))
    .sort();
  const expectedCommandFiles = commands.map((command) => `${adapterSlug(command)}.md`).sort();
  const manifestCommandFiles = config.commands.map((name) => `${name}.md`).sort();
  if (commandFiles.length !== EXPECTED_COMMANDS || JSON.stringify(commandFiles) !== JSON.stringify(expectedCommandFiles)) {
    fail(`commands/ must contain exactly the ${EXPECTED_COMMANDS} registry-derived PMOS adapters`);
  }
  if (JSON.stringify(manifestCommandFiles) !== JSON.stringify(expectedCommandFiles)) {
    fail('manifest command ids do not exactly enumerate commands/');
  }
  for (const command of commands) {
    const filename = path.join(commandDir, `${adapterSlug(command)}.md`);
    if (fs.readFileSync(filename, 'utf8') !== renderCommandAdapter(command)) {
      fail(`stale or non-deterministic command adapter: ${filename}`);
    }
  }

  const inventory = loadJson(path.join(addonRoot, 'registry', 'addon-inventory.json'));
  if (
    inventory.sourceSkills !== EXPECTED_SOURCE_SKILLS ||
    inventory.kernelSkills !== 1 ||
    inventory.packagedSkills !== EXPECTED_PACKAGED_SKILLS ||
    inventory.agents !== EXPECTED_AGENTS ||
    inventory.invocationSurfaces?.total !== EXPECTED_COMMANDS
  ) {
    fail('addon inventory counts do not match the required PMOS surface');
  }
  validateNativeAgentSources(addonRoot, config.agents);
  return commands;
}

function translateHostAssumptions(text) {
  const replacements = [
    ['Claude Code / Cursor / Cowork', 'the current Codex workspace'],
    ['Claude Code', 'Codex'],
    ['Claude', 'Codex'],
    ['AskUserQuestion', 'native structured user input'],
    ['AskQuestion', 'native structured user input'],
    ['Task tool', 'native subagent delegation'],
    ['Skill tool', 'native skill invocation'],
    ['Read tool', 'native file-reading capability'],
    ['Write tool', 'native file-editing capability'],
    ['WebSearch', 'native web-search capability'],
    ['WebFetch', 'native web-fetch capability']
  ];
  let result = String(text);
  for (const [from, to] of replacements) result = result.split(from).join(to);
  result = result.replace(/\/pm-os:([a-z0-9-]+)/gi, '$$$1');
  return result;
}

export function adapterSlug(command) {
  const canonicalStem = path.basename(path.dirname(command.canonical_file));
  const aliases = {
    'pm-help': 'pm-os-help',
    'pm-status': 'pm-os-status',
    'pm-review': 'pm-os-review'
  };
  if (aliases[canonicalStem]) return aliases[canonicalStem];
  const slug = String(command.slug);
  return slug.startsWith('pm-os-') ? slug : `pm-os-${slug}`;
}

export function renderCommandAdapter(command) {
  const slug = adapterSlug(command);
  const source = `.aiwg/addons/pm-os/${command.canonical_file}`;
  const description = translateHostAssumptions(command.description || 'PMOS command');
  const argumentHint = String(command.argument_hint || '').trim();
  const frontmatter = ['---', `description: ${JSON.stringify(`PMOS: ${description}`)}`];
  if (argumentHint) frontmatter.push(`argument-hint: ${JSON.stringify(argumentHint)}`);
  frontmatter.push('---');

  const policy = [
    'Read the canonical skill named below before acting; it remains the source of truth.',
    'Use the arguments supplied with this invocation as `$ARGUMENTS` and preserve their order.',
    'Map exact host tool labels in the canonical skill to the equivalent native Codex capability.',
    'Map legacy slash-command references to the corresponding `$pm-os-*` adapter or skill.',
    'Use native structured user input when available; otherwise ask one concise inline question.'
  ];
  if (command.setup_required) policy.push('Verify the PMOS Context and project prerequisites before execution.');
  if (command.writes_files) policy.push('Keep every write inside the canonical PMOS destination described by the skill.');
  if (command.requires_confirmation) {
    policy.push("Obtain the skill's required explicit confirmation before writes or external actions.");
  } else {
    policy.push('Do not introduce a new confirmation gate unless the requested action requires one.');
  }

  const body = policy.map((line, index) => `${index + 1}. ${line}`).join('\n');
  return `${frontmatter.join('\n')}\n<!-- ${LEGACY_MARKER} -->\n\n# PMOS adapter: $${slug}\n\nCanonical skill: \`${source}\`\n\n${body}\n`;
}

function yamlDoubleQuoted(value) {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, ' ')
    .trim();
}

function renderQuickref(sourceFile) {
  const content = fs.readFileSync(sourceFile, 'utf8');
  const match = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match || !/^kernel:\s*true\s*$/m.test(match[1])) fail('pm-os-quickref is not a kernel skill');
  const name = match[1].match(/^name:\s*["']?([^"'\n]+)["']?\s*$/m)?.[1]?.trim();
  let description = match[1].match(/^description:\s*["']?([^\n]+?)["']?\s*$/m)?.[1]?.trim();
  if (name !== QUICKREF || !description) fail('pm-os-quickref frontmatter is invalid');
  if (description.length > 500) {
    description = description.slice(0, 497);
    const lastSpace = description.lastIndexOf(' ');
    if (lastSpace > 450) description = description.slice(0, lastSpace);
    description += '...';
  }
  return `---\nname: "${yamlDoubleQuoted(name)}"\ndescription: "${yamlDoubleQuoted(description)}"\nplatforms: [codex]\n---\n\n${match[2].trim()}\n`;
}

function renderQuickrefMetadata(content) {
  const match = content.match(/^description:\s*("(?:[^"\\]|\\.)*")\s*$/m);
  if (!match) fail('rendered pm-os-quickref description is invalid');
  let description;
  try {
    description = JSON.parse(match[1]);
  } catch (error) {
    fail(`rendered pm-os-quickref description is not valid JSON: ${error.message}`);
  }
  const displayName = QUICKREF
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
  return `interface:\n  display_name: "${yamlDoubleQuoted(displayName)}"\n  short_description: "${yamlDoubleQuoted(description)}"\n`;
}

function atomicWrite(filename, content) {
  const temporary = path.join(path.dirname(filename), `.${path.basename(filename)}.pm-os-${process.pid}.tmp`);
  try {
    fs.writeFileSync(temporary, content, { encoding: 'utf8', mode: 0o644, flag: 'wx' });
    fs.renameSync(temporary, filename);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function tomlBasicString(content, key, filename) {
  const match = content.match(new RegExp(`^${key}\\s*=\\s*("(?:[^"\\\\]|\\\\.)*")\\s*$`, 'm'));
  if (!match) fail(`missing ${key} TOML contract in ${filename}`);
  try {
    return JSON.parse(match[1]);
  } catch (error) {
    fail(`invalid ${key} TOML string in ${filename}: ${error.message}`);
  }
}

function validateNativeAgentSources(addonRoot, manifestAgents) {
  const directory = path.join(addonRoot, 'codex', 'agents');
  const directoryStat = lstatIfExists(directory);
  if (!directoryStat || !directoryStat.isDirectory() || directoryStat.isSymbolicLink()) {
    fail(`missing or unsafe native Codex agent directory: ${directory}`);
  }
  const expected = manifestAgents.map((name) => `pm-os-${name}.toml`).sort();
  const entries = fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  if (
    entries.length !== EXPECTED_NATIVE_AGENTS ||
    JSON.stringify(entries.map((entry) => entry.name)) !== JSON.stringify(expected)
  ) {
    fail(`codex/agents must contain exactly the ${EXPECTED_NATIVE_AGENTS} manifest-derived PMOS TOML files`);
  }
  for (const entry of entries) {
    const filename = path.join(directory, entry.name);
    const stat = fs.lstatSync(filename);
    if (!entry.isFile() || !stat.isFile() || stat.isSymbolicLink()) {
      fail(`native Codex agent must be a regular file: ${filename}`);
    }
    const content = fs.readFileSync(filename, 'utf8');
    if (content.split(/\r?\n/, 1)[0] !== NATIVE_AGENT_MARKER) {
      fail(`missing exact AIWG-managed PMOS ownership marker in ${filename}`);
    }
    const expectedName = entry.name.slice('pm-os-'.length, -'.toml'.length);
    if (tomlBasicString(content, 'name', filename) !== expectedName) {
      fail(`native Codex agent name does not match its filename: ${filename}`);
    }
    if (!tomlBasicString(content, 'description', filename).trim()) fail(`empty native agent description: ${filename}`);
    if (!['read-only', 'workspace-write'].includes(tomlBasicString(content, 'sandbox_mode', filename))) {
      fail(`unsafe native agent sandbox_mode: ${filename}`);
    }
    if (!tomlBasicString(content, 'developer_instructions', filename).trim()) {
      fail(`empty native agent developer_instructions: ${filename}`);
    }
  }
}

function readNativeSource(addonRoot, relative, label) {
  const filename = path.resolve(addonRoot, relative);
  if (!filename.startsWith(`${addonRoot}${path.sep}`)) fail(`${label} escapes addon root: ${relative}`);
  const stat = lstatIfExists(filename);
  if (!stat || !stat.isFile() || stat.isSymbolicLink()) fail(`missing or unsafe ${label}: ${relative}`);
  return { filename, content: fs.readFileSync(filename, 'utf8') };
}

function shellQuote(value) {
  const text = String(value);
  if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(text)) return text;
  return `'${text.replaceAll("'", "'\"'\"'")}'`;
}

function validateMcpExample(content, filename) {
  if (!content.slice(0, 512).includes(LEGACY_MARKER)) {
    fail(`missing PMOS ownership marker in ${filename}`);
  }
  const names = [...content.matchAll(/^\[mcp_servers\.([a-z0-9][a-z0-9-]*)\]\s*$/gm)]
    .map((match) => match[1]);
  if (names.length !== EXPECTED_MCP_SERVERS || new Set(names).size !== EXPECTED_MCP_SERVERS) {
    fail(`expected ${EXPECTED_MCP_SERVERS} unique disabled MCP server tables in ${filename}`);
  }
  if (JSON.stringify([...names].sort()) !== JSON.stringify(EXPECTED_MCP_NAMES)) {
    fail(`unexpected PMOS MCP server inventory in ${filename}`);
  }
  const sections = content.split(/^\[mcp_servers\.[a-z0-9][a-z0-9-]*\]\s*$/gm).slice(1);
  for (const section of sections) {
    if (!/^enabled\s*=\s*false\s*$/m.test(section) || !/^required\s*=\s*false\s*$/m.test(section)) {
      fail(`all PMOS MCP example servers must be disabled and optional in ${filename}`);
    }
  }
}

function renderNativeHookGroups(layout) {
  const source = readNativeSource(layout.addonRoot, CODEX_HOOK_TEMPLATE, 'Codex hook template');
  let template;
  try {
    template = JSON.parse(source.content);
  } catch (error) {
    fail(`cannot read valid JSON from ${source.filename}: ${error.message}`);
  }
  if (!isPlainObject(template) || !String(template.description || '').includes(LEGACY_MARKER)) {
    fail('Codex hook template is missing its PMOS ownership marker');
  }
  if (!isPlainObject(template.hooks)) fail('Codex hook template hooks must be an object');
  if (JSON.stringify(Object.keys(template.hooks).sort()) !== JSON.stringify(NATIVE_HOOKS.map((item) => item.event).sort())) {
    fail(`Codex hook template must contain exactly ${EXPECTED_NATIVE_HOOKS} PMOS hook groups`);
  }

  const groups = new Map();
  const scripts = [];
  for (const definition of NATIVE_HOOKS) {
    const script = readNativeSource(layout.addonRoot, definition.source, `${definition.event} hook script`);
    if (!script.content.slice(0, 512).includes(LEGACY_MARKER)) {
      fail(`missing PMOS ownership marker in ${script.filename}`);
    }
    const destination = path.join(layout.projectRoot, definition.destination);
    const values = template.hooks[definition.event];
    if (!Array.isArray(values) || values.length !== 1 || !isPlainObject(values[0])) {
      fail(`${definition.event} hook template must contain exactly one group`);
    }
    const group = JSON.parse(JSON.stringify(values[0]));
    if (!Array.isArray(group.hooks) || group.hooks.length !== 1 || !isPlainObject(group.hooks[0])) {
      fail(`${definition.event} hook template group must contain exactly one command hook`);
    }
    if (group.hooks[0].type !== 'command' || group.hooks[0].command !== definition.token) {
      fail(`${definition.event} hook template command token is invalid`);
    }
    group.hooks[0].command = `/usr/bin/env python3 ${shellQuote(destination)}`;
    groups.set(definition.event, group);
    scripts.push({
      kind: 'hook-script',
      destination,
      content: script.content,
      label: `${definition.event} hook script`
    });
  }
  return { description: template.description, groups, scripts };
}

function hookCommandStrings(group) {
  if (!isPlainObject(group) || !Array.isArray(group.hooks)) return [];
  return group.hooks
    .filter((hook) => isPlainObject(hook) && typeof hook.command === 'string')
    .map((hook) => hook.command);
}

function containsPmosHookHint(group) {
  const serialized = JSON.stringify(group);
  return serialized.includes('/.codex/hooks/pm-os/') ||
    serialized.includes('\\.codex\\hooks\\pm-os\\') ||
    serialized.includes(LEGACY_MARKER);
}

function mergeNativeHooks(layout, native) {
  const destination = path.join(layout.projectRoot, '.codex', 'hooks.json');
  assertNoSymlinkComponents(layout.projectRoot, destination);
  const stat = lstatIfExists(destination);
  if (stat && (!stat.isFile() || stat.isSymbolicLink())) {
    fail(`refusing non-file Codex hook config: ${destination}`);
  }

  let currentText = null;
  let current;
  if (stat) {
    currentText = fs.readFileSync(destination, 'utf8');
    try {
      current = JSON.parse(currentText);
    } catch (error) {
      fail(`cannot merge malformed Codex hook config ${destination}: ${error.message}`);
    }
    if (!isPlainObject(current)) fail(`Codex hook config must be a JSON object: ${destination}`);
  } else {
    current = { description: native.description, hooks: {} };
  }
  if (current.hooks === undefined) current.hooks = {};
  if (!isPlainObject(current.hooks)) fail(`Codex hook config hooks must be an object: ${destination}`);

  const merged = JSON.parse(JSON.stringify(current));
  const ownedLocations = new Map();
  for (const [event, groups] of Object.entries(merged.hooks)) {
    if (!Array.isArray(groups)) fail(`Codex hook event ${event} must be an array: ${destination}`);
    groups.forEach((group, index) => {
      if (!isPlainObject(group)) fail(`Codex hook group ${event}[${index}] must be an object: ${destination}`);
      const commands = hookCommandStrings(group);
      const owned = NATIVE_HOOKS.filter((definition) => {
        const desired = native.groups.get(definition.event);
        return commands.includes(desired.hooks[0].command);
      });
      if (owned.length === 0) {
        if (containsPmosHookHint(group)) {
          fail(`refusing unexpected PMOS hook content at ${event}[${index}] in ${destination}`);
        }
        return;
      }
      if (
        owned.length !== 1 ||
        owned[0].event !== event ||
        commands.length !== 1 ||
        group.hooks.length !== 1
      ) {
        fail(`refusing mixed or misplaced PMOS hook content at ${event}[${index}] in ${destination}`);
      }
      if (ownedLocations.has(event)) fail(`duplicate PMOS ${event} hook group in ${destination}`);
      ownedLocations.set(event, index);
    });
  }

  for (const definition of NATIVE_HOOKS) {
    const desired = native.groups.get(definition.event);
    const groups = merged.hooks[definition.event] || [];
    if (!Array.isArray(groups)) fail(`Codex hook event ${definition.event} must be an array: ${destination}`);
    if (ownedLocations.has(definition.event)) groups[ownedLocations.get(definition.event)] = desired;
    else groups.push(desired);
    merged.hooks[definition.event] = groups;
  }

  const semanticallyUnchanged = currentText !== null && JSON.stringify(current) === JSON.stringify(merged);
  return {
    kind: 'hook-config',
    destination,
    content: semanticallyUnchanged ? currentText : `${JSON.stringify(merged, null, 2)}\n`,
    label: 'Codex hook config'
  };
}

function planManagedFile(projectRoot, artifact) {
  assertNoSymlinkComponents(projectRoot, artifact.destination);
  const stat = lstatIfExists(artifact.destination);
  if (!stat) return { ...artifact, action: 'create' };
  if (!stat.isFile() || stat.isSymbolicLink()) fail(`refusing non-file ${artifact.label}: ${artifact.destination}`);
  const current = fs.readFileSync(artifact.destination, 'utf8');
  if (current === artifact.content) return { ...artifact, action: 'unchanged' };
  if (artifact.kind === 'hook-config') return { ...artifact, action: 'update' };
  if (!current.slice(0, 512).includes(LEGACY_MARKER)) {
    fail(`refusing to overwrite non-PMOS ${artifact.label}: ${artifact.destination}`);
  }
  return { ...artifact, action: 'update' };
}

function planNativeLifecycle(layout) {
  const native = renderNativeHookGroups(layout);
  const hookDir = path.join(layout.projectRoot, '.codex', 'hooks', 'pm-os');
  assertNoSymlinkComponents(layout.projectRoot, hookDir);
  const hookDirStat = lstatIfExists(hookDir);
  if (hookDirStat && (!hookDirStat.isDirectory() || hookDirStat.isSymbolicLink())) {
    fail(`refusing non-directory PMOS hook target: ${hookDir}`);
  }
  if (hookDirStat) {
    const expected = new Set(NATIVE_HOOKS.map((item) => path.basename(item.destination)));
    const unexpected = fs.readdirSync(hookDir).filter((name) => !expected.has(name));
    if (unexpected.length > 0) {
      fail(`refusing unexpected content in PMOS hook directory: ${unexpected.join(', ')}`);
    }
  }

  const mcp = readNativeSource(layout.addonRoot, CODEX_MCP_EXAMPLE, 'Codex MCP example');
  validateMcpExample(mcp.content, mcp.filename);
  const artifacts = [
    ...native.scripts,
    {
      kind: 'mcp-example',
      destination: path.join(layout.projectRoot, '.codex', 'pm-os-mcp.example.toml'),
      content: mcp.content,
      label: 'Codex MCP example'
    },
    mergeNativeHooks(layout, native)
  ];
  return artifacts.map((artifact) => planManagedFile(layout.projectRoot, artifact));
}

function planFingerprint(projectRoot, plans) {
  const hash = crypto.createHash('sha256');
  for (const item of [...plans].sort((a, b) => a.destination.localeCompare(b.destination))) {
    hash.update(item.kind || 'command');
    hash.update('\0');
    hash.update(path.relative(projectRoot, item.destination));
    hash.update('\0');
    hash.update(crypto.createHash('sha256').update(item.content).digest('hex'));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function assertExpectedTarget(projectRoot, target, expected) {
  const resolved = path.resolve(target || expected);
  if (resolved !== expected) fail(`refusing unexpected provider target: ${resolved}; expected ${expected}`);
  assertNoSymlinkComponents(projectRoot, resolved);
  const stat = lstatIfExists(resolved);
  if (stat && (!stat.isDirectory() || stat.isSymbolicLink())) {
    fail(`provider target is not a directory: ${resolved}`);
  }
  return resolved;
}

export function deployCommandAdapters(argv) {
  const cfg = parseCliArgs(argv);
  const layout = resolveProjectLayout(cfg.source, {
    projectRoot: cfg.projectRoot,
    aiwgRoot: cfg.aiwgRoot
  });
  const commands = validateSource(layout);
  const target = assertExpectedTarget(
    layout.projectRoot,
    cfg.target,
    path.join(layout.projectRoot, '.codex', 'commands')
  );
  const outputs = new Map();
  for (const command of commands) {
    const name = `${adapterSlug(command)}.md`;
    outputs.set(name, fs.readFileSync(path.join(layout.addonRoot, 'commands', name), 'utf8'));
  }
  if (outputs.size !== EXPECTED_COMMANDS) fail('command adapter names collide');

  const plan = [];
  for (const [name, content] of [...outputs.entries()].sort()) {
    const destination = path.join(target, name);
    if (!fs.existsSync(destination)) {
      plan.push({ kind: 'command', destination, content, action: 'create' });
      continue;
    }
    const stat = fs.lstatSync(destination);
    if (!stat.isFile() || stat.isSymbolicLink()) fail(`refusing non-file command target: ${destination}`);
    const current = fs.readFileSync(destination, 'utf8');
    if (current === content) plan.push({ kind: 'command', destination, content, action: 'unchanged' });
    else if (current.slice(0, 512).includes(LEGACY_MARKER)) plan.push({ kind: 'command', destination, content, action: 'update' });
    else fail(`refusing to overwrite non-PMOS command artifact: ${destination}`);
  }

  if (fs.existsSync(target)) {
    const expected = new Set(outputs.keys());
    for (const entry of fs.readdirSync(target)) {
      if (!entry.startsWith('pm-os-') || !entry.endsWith('.md') || expected.has(entry)) continue;
      const filename = path.join(target, entry);
      const stat = fs.lstatSync(filename);
      if (!stat.isFile() || stat.isSymbolicLink()) fail(`refusing unexpected PMOS command target: ${filename}`);
      if (fs.readFileSync(filename, 'utf8').slice(0, 512).includes(LEGACY_MARKER)) {
        fail(`refusing a prune plan for stale PMOS command adapter: ${filename}`);
      }
      fail(`refusing unexpected PMOS command collision: ${filename}`);
    }
  }

  const lifecyclePlan = planNativeLifecycle(layout);
  const changed = plan.filter((item) => item.action !== 'unchanged');
  const lifecycleChanged = lifecyclePlan.filter((item) => item.action !== 'unchanged');
  const fingerprint = planFingerprint(layout.projectRoot, [...plan, ...lifecyclePlan]);
  console.log('PMOS Codex command adapters');
  console.log(`  Source: ${layout.addonRoot}`);
  console.log(`  Target: ${target}`);
  if (cfg.dryRun) console.log('  [DRY RUN — read only]');
  for (const item of changed) console.log(`  ${cfg.dryRun ? '[dry-run] ' : ''}${item.action}: ${path.basename(item.destination)}`);
  for (const item of lifecycleChanged) {
    console.log(`  ${cfg.dryRun ? '[dry-run] ' : ''}${item.action}: ${path.relative(layout.projectRoot, item.destination)}`);
  }
  console.log(`  Plan fingerprint: sha256:${fingerprint}`);

  if (!cfg.dryRun) {
    fs.mkdirSync(target, { recursive: true });
    fs.mkdirSync(path.join(layout.projectRoot, '.codex', 'hooks', 'pm-os'), { recursive: true });
    for (const item of changed) atomicWrite(item.destination, item.content);
    for (const item of lifecycleChanged.filter((item) => item.kind !== 'hook-config')) {
      atomicWrite(item.destination, item.content);
    }
    for (const item of lifecycleChanged.filter((item) => item.kind === 'hook-config')) {
      atomicWrite(item.destination, item.content);
    }
    for (const item of plan) {
      if (fs.readFileSync(item.destination, 'utf8') !== item.content) fail(`post-write verification failed: ${item.destination}`);
    }
    for (const item of lifecyclePlan) {
      if (fs.readFileSync(item.destination, 'utf8') !== item.content) fail(`post-write verification failed: ${item.destination}`);
    }
  }
  console.log(
    `Summary: expected=${EXPECTED_COMMANDS} planned=${plan.length} changed=${changed.length} ` +
    `unchanged=${plan.length - changed.length} hooks=${EXPECTED_NATIVE_HOOKS} mcp-example=1 ` +
    `lifecycle-changed=${lifecycleChanged.length} pruned=0`
  );
  return 0;
}

export function deployKernelQuickref(argv) {
  const cfg = parseCliArgs(argv);
  const layout = resolveProjectLayout(cfg.source, {
    projectRoot: cfg.projectRoot,
    aiwgRoot: cfg.aiwgRoot
  });
  validateSource(layout);
  const target = assertExpectedTarget(
    layout.projectRoot,
    cfg.target,
    path.join(layout.projectRoot, '.agents', 'skills')
  );
  const source = path.join(layout.addonRoot, 'skills', QUICKREF, 'SKILL.md');
  const content = renderQuickref(source);
  const metadataContent = renderQuickrefMetadata(content);
  const skillDir = path.join(target, QUICKREF);
  const destination = path.join(skillDir, 'SKILL.md');
  const marker = path.join(skillDir, '.aiwg-managed');
  const metadataDir = path.join(skillDir, 'agents');
  const metadata = path.join(metadataDir, 'openai.yaml');

  assertNoSymlinkComponents(layout.projectRoot, skillDir);
  assertNoSymlinkComponents(layout.projectRoot, destination);
  assertNoSymlinkComponents(layout.projectRoot, marker);
  assertNoSymlinkComponents(layout.projectRoot, metadata);
  let action = 'create';
  let markerContent = null;
  if (fs.existsSync(skillDir)) {
    if (!fs.statSync(skillDir).isDirectory() || fs.lstatSync(skillDir).isSymbolicLink()) {
      fail(`refusing non-directory quickref target: ${skillDir}`);
    }
    const unexpected = fs.readdirSync(skillDir).filter((name) => !['SKILL.md', '.aiwg-managed', 'agents'].includes(name));
    if (unexpected.length > 0) fail(`refusing to alter quickref directory with unmanaged files: ${unexpected.join(', ')}`);

    if (fs.existsSync(metadataDir)) {
      const metadataDirStat = fs.lstatSync(metadataDir);
      if (!metadataDirStat.isDirectory() || metadataDirStat.isSymbolicLink()) {
        fail(`refusing unsafe quickref metadata directory: ${metadataDir}`);
      }
      const unexpectedMetadata = fs.readdirSync(metadataDir)
        .filter((name) => name !== 'openai.yaml')
        .map((name) => `agents/${name}`);
      if (unexpectedMetadata.length > 0) {
        fail(`refusing to alter quickref directory with unmanaged files: ${unexpectedMetadata.join(', ')}`);
      }
    }
    for (const filename of [destination, marker, metadata]) {
      if (!fs.existsSync(filename)) continue;
      const stat = fs.lstatSync(filename);
      if (!stat.isFile() || stat.isSymbolicLink()) fail(`refusing unsafe quickref artifact: ${filename}`);
    }

    if (fs.existsSync(marker)) {
      markerContent = fs.readFileSync(marker, 'utf8');
      if (!['pm-os\n', 'aiwg\n'].includes(markerContent)) {
        fail(`refusing unrecognized quickref ownership marker: ${marker}`);
      }
    }
    if (fs.existsSync(destination)) {
      const current = fs.readFileSync(destination, 'utf8');
      if (!markerContent) fail(`refusing to overwrite unowned quickref: ${destination}`);
      const metadataMatches = fs.existsSync(metadata) && fs.readFileSync(metadata, 'utf8') === metadataContent;
      if (current === content && metadataMatches) action = 'unchanged';
      else action = 'update';
    } else if (!markerContent) {
      fail(`refusing unowned quickref directory: ${skillDir}`);
    }
  }

  console.log('PMOS Codex kernel quickref');
  console.log(`  Source: ${source}`);
  console.log(`  Target: ${destination}`);
  if (cfg.dryRun) console.log('  [DRY RUN — read only]');
  console.log(`  ${cfg.dryRun ? '[dry-run] ' : ''}${action}: ${QUICKREF}`);

  if (!cfg.dryRun && action !== 'unchanged') {
    fs.mkdirSync(skillDir, { recursive: true });
    fs.mkdirSync(metadataDir, { recursive: true });
    atomicWrite(destination, content);
    atomicWrite(metadata, metadataContent);
    if (!markerContent) atomicWrite(marker, 'pm-os\n');
  }
  if (!cfg.dryRun && (
    fs.readFileSync(destination, 'utf8') !== content ||
    fs.readFileSync(metadata, 'utf8') !== metadataContent ||
    !['pm-os\n', 'aiwg\n'].includes(fs.readFileSync(marker, 'utf8'))
  )) {
    fail('post-write verification failed for pm-os-quickref');
  }
  console.log(`Summary: expected=1 planned=1 changed=${action === 'unchanged' ? 0 : 1} unchanged=${action === 'unchanged' ? 1 : 0} pruned=0 standard-skills-indexed=${EXPECTED_SOURCE_SKILLS}`);
  return 0;
}
