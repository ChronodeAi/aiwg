def render_mcp_example(servers: dict[str, Any]) -> str:
    lines = [
        f"# {MARKER}",
        "# Opt-in example only. Copy selected tables into .codex/config.toml,",
        "# authenticate where required, then change enabled to true.",
        "",
    ]
    oauth_names = {"notion", "linear", "atlassian", "github"}
    for name in EXPECTED_MCP_NAMES:
        server = servers[name]
        if not isinstance(server, dict):
            raise GenerationError(f"MCP definition for {name} must be an object")
        lines.append(f"[mcp_servers.pm-os-{name}]")
        server_type = server.get("type")
        if server_type == "http":
            url = server.get("url")
            if not isinstance(url, str) or not url.startswith("https://"):
                raise GenerationError(f"MCP HTTP server {name} lacks a safe HTTPS URL")
            lines.append(f"url = {toml_string(url)}")
            if name in oauth_names:
                lines.append('auth = "oauth"')
        elif server_type == "stdio":
            command = server.get("command")
            args = server.get("args", [])
            env = server.get("env", {})
            if not isinstance(command, str) or not isinstance(args, list) or not isinstance(env, dict):
                raise GenerationError(f"invalid STDIO MCP definition for {name}")
            lines.append(f"command = {toml_string(command)}")
            lines.append(
                "args = [" + ", ".join(toml_string(str(value)) for value in args) + "]"
            )
            if env:
                lines.append(
                    "env_vars = ["
                    + ", ".join(toml_string(str(key)) for key in sorted(env))
                    + "]"
                )
        else:
            raise GenerationError(f"unsupported MCP type for {name}: {server_type!r}")
        lines.extend(["enabled = false", "required = false", ""])

    rendered = "\n".join(lines)
    try:
        parsed = tomllib.loads(rendered)
    except tomllib.TOMLDecodeError as exc:
        raise GenerationError(f"generated invalid MCP TOML: {exc}") from exc
    if len(parsed.get("mcp_servers", {})) != len(EXPECTED_MCP_NAMES):
        raise GenerationError("generated MCP example does not contain exactly six servers")
    return rendered


def expected_outputs(root: Path) -> dict[Path, str]:
    agents, commands, servers = validate_sources(root)
    outputs: dict[Path, str] = {}
    for agent in agents:
        path = root / ".codex/agents" / f"pm-os-{agent['agent_id']}.toml"
        outputs[path] = render_agent(root, agent)
    for command in commands:
        path = root / ".codex/commands" / f"{adapter_slug(command)}.md"
        outputs[path] = render_command(command)
    outputs.update(render_hooks(root))
    outputs[root / ".codex/pm-os-mcp.example.toml"] = render_mcp_example(servers)
    return outputs


def generated_files_in(
    directory: Path,
    pattern: str,
    markers: tuple[str, ...] = (MARKER,),
) -> set[Path]:
    if not directory.is_dir():
        return set()
    found: set[Path] = set()
    for path in directory.glob(pattern):
        if not path.is_file():
            continue
        try:
            prefix = path.read_text(encoding="utf-8")[:512]
        except OSError:
            continue
        if any(marker in prefix for marker in markers):
            found.add(path)
    return found


def check_outputs(root: Path, outputs: dict[Path, str]) -> int:
    problems: list[str] = []
    for path, expected in sorted(outputs.items(), key=lambda item: str(item[0])):
        if not path.is_file():
            problems.append(f"missing: {path.relative_to(root)}")
            continue
        try:
            actual = path.read_text(encoding="utf-8")
        except OSError as exc:
            problems.append(f"unreadable: {path.relative_to(root)} ({exc})")
            continue
        if actual != expected:
            problems.append(f"stale: {path.relative_to(root)}")

    expected_paths = set(outputs)
    managed = generated_files_in(root / ".codex/commands", "pm-os-*.md")
    managed |= generated_files_in(
        root / ".codex/agents",
        "pm-os-*.toml",
        (AGENT_MARKER, MARKER),
    )
    for path in sorted(managed - expected_paths):
        problems.append(f"unexpected generated file: {path.relative_to(root)}")

    if problems:
        print("Codex PMOS adapters are not current:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    print(
        "Codex PMOS adapters are current: "
        "26 commands, 12 agents, 2 hook scripts, 6 opt-in MCP servers."
    )
    return 0


def write_outputs(root: Path, outputs: dict[Path, str]) -> int:
    for path, content in sorted(outputs.items(), key=lambda item: str(item[0])):
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            current = path.read_text(encoding="utf-8")
            ownership_markers = (
                (AGENT_MARKER, MARKER)
                if path.parent == root / ".codex/agents"
                else (MARKER,)
            )
            if current != content and not any(
                marker in current[:512] for marker in ownership_markers
            ):
                raise GenerationError(
                    f"refusing to overwrite non-generated file in PMOS namespace: {path}"
                )
        path.write_text(content, encoding="utf-8")

    expected_paths = set(outputs)
    managed = generated_files_in(root / ".codex/commands", "pm-os-*.md")
    managed |= generated_files_in(
        root / ".codex/agents",
        "pm-os-*.toml",
        (AGENT_MARKER, MARKER),
    )
    for stale in sorted(managed - expected_paths):
        stale.unlink()

    print(
        "Generated Codex PMOS adapters: "
        "26 commands, 12 agents, 2 hook scripts, 6 disabled MCP examples."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify deterministic outputs without writing files",
    )
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    try:
        outputs = expected_outputs(root)
        return check_outputs(root, outputs) if args.check else write_outputs(root, outputs)
    except (GenerationError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
