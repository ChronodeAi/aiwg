#!/usr/bin/env python3
"""Generate the project-local Codex adapter surface for PMOS.

The PMOS registries and canonical Markdown files remain the source of truth.
This generator only owns PMOS-namespaced files in .codex plus the two hook
entrypoints declared below. It deliberately leaves AIWG-managed files alone.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import shlex
import sys
import tomllib
from pathlib import Path
from typing import Any


GENERATOR = "bin/generate-codex-adapters.py"
MARKER = f"Generated by {GENERATOR}; do not edit."
AGENT_MARKER = "Generated by PMOS for OpenAI Codex; AIWG-managed."
ADDON_ROOT_REL = ".aiwg/addons/pm-os"
SKILL_BROWSER_PATH = "skills/skill-browser/SKILL.md"
EXPECTED_SKILL_COUNT = 230
EXPECTED_AGENT_COUNT = 12
EXPECTED_COMMAND_COUNT = 26
EXPECTED_MCP_NAMES = (
    "lenny-podcast",
    "notion",
    "linear",
    "atlassian",
    "github",
    "perplexity",
)


class GenerationError(RuntimeError):
    """Raised when a source registry cannot produce a safe deterministic set."""


def load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise GenerationError(f"cannot read valid JSON from {path}: {exc}") from exc


def parse_scalar(raw: str) -> Any:
    raw = raw.strip()
    if not raw:
        return ""
    if raw in {"true", "false"}:
        return raw == "true"
    if raw[0:1] in {"\"", "'"}:
        try:
            return ast.literal_eval(raw)
        except (SyntaxError, ValueError):
            return raw.strip("\"'")
    return raw


def parse_markdown_frontmatter(path: Path) -> tuple[dict[str, Any], str]:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise GenerationError(f"missing YAML frontmatter in {path}")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration as exc:
        raise GenerationError(f"unterminated YAML frontmatter in {path}") from exc

    metadata: dict[str, Any] = {}
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise GenerationError(f"unsupported frontmatter line in {path}: {line!r}")
        key, value = line.split(":", 1)
        metadata[key.strip()] = parse_scalar(value)
    body = "\n".join(lines[end + 1 :]).strip() + "\n"
    return metadata, body


def translate_host_assumptions(text: str) -> str:
    """Translate host-specific wording without changing PMOS domain content."""

    phrase_replacements = (
        ("Claude Code / Cursor / Cowork", "the current Codex workspace"),
        ("Claude Code", "Codex"),
        ("Claude", "Codex"),
        ("AskUserQuestion", "native structured user input"),
        ("AskQuestion", "native structured user input"),
        ("Task tool", "native subagent delegation"),
        ("Skill tool", "native skill invocation"),
        ("Read tool", "native file-reading capability"),
        ("Write tool", "native file-editing capability"),
        ("WebSearch", "native web-search capability"),
        ("WebFetch", "native web-fetch capability"),
    )
    for old, new in phrase_replacements:
        text = text.replace(old, new)

    text = re.sub(
        r"/pm-os:([a-z0-9-]+)",
        lambda match: f"$pm-os-{match.group(1)}",
        text,
        flags=re.IGNORECASE,
    )
    command_names = (
        "agent-builder",
        "capture-memory",
        "daily-drip",
        "feedback",
        "help",
        "import-ai-memory",
        "project",
        "testimonial",
        "upgrade",
        "assumptions",
        "stakeholder",
        "opportunity",
        "decisions",
        "coaching",
        "research",
        "strategy",
        "measure",
        "meeting",
        "framework",
        "status",
        "review",
        "skill",
        "start",
        "tidy",
        "prd",
    )
    pattern = re.compile(
        r"(?<![A-Za-z0-9_.-])/([A-Za-z0-9-]+)(?![A-Za-z0-9_.-])",
        re.IGNORECASE,
    )

    def replace_command(match: re.Match[str]) -> str:
        command = match.group(1).lower()
        if command not in command_names:
            return match.group(0)
        return f"$pm-os-{command}"

    return pattern.sub(replace_command, text)


def qualify_addon_paths(text: str) -> str:
    """Make add-on-local runtime references unambiguous from the workspace root."""

    text = text.replace("", f"{ADDON_ROOT_REL}/")
    text = text.replace("knowledge/", f"{ADDON_ROOT_REL}/knowledge/")
    local_roots = "skills|knowledge|bin|rules|references|templates|examples|registry|runtime"
    return re.sub(
        rf"(?<![A-Za-z0-9_./-])({local_roots})/",
        lambda match: f"{ADDON_ROOT_REL}/{match.group(1)}/",
        text,
    )


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def adapter_slug(command: dict[str, Any]) -> str:
    slug = str(command["slug"])
    canonical_stem = Path(str(command["canonical_file"])).parent.name
    canonical_aliases = {
        "pm-help": "pm-os-help",
        "pm-status": "pm-os-status",
        "pm-review": "pm-os-review",
    }
    if canonical_stem in canonical_aliases:
        return canonical_aliases[canonical_stem]
    if slug.startswith("pm-os-"):
        return slug
    return f"pm-os-{slug}"


def validate_sources(root: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    addon_root = root / ADDON_ROOT_REL
    registry = addon_root / "registry"
    skills = load_json(registry / "skills.json")
    agents = load_json(registry / "agents.json")
    commands = load_json(registry / "commands.json")
    mcp = load_json(addon_root / ".mcp.json")

    if not isinstance(skills, list) or not isinstance(agents, list) or not isinstance(commands, list):
        raise GenerationError("PMOS skill, agent, and command registries must be JSON arrays")

    active_skills = [item for item in skills if item.get("status") == "active"]
    if len(active_skills) != EXPECTED_SKILL_COUNT:
        raise GenerationError(
            f"expected {EXPECTED_SKILL_COUNT} active skills, found {len(active_skills)}"
        )
    skill_paths = {str(item.get("path", "")) for item in active_skills}
    if len(skill_paths) != EXPECTED_SKILL_COUNT:
        raise GenerationError("active skill registry contains duplicate or empty paths")
    for skill_path in sorted(skill_paths):
        if not (addon_root / skill_path).is_file():
            raise GenerationError(f"registered skill is missing: {skill_path}")

    active_agents = [item for item in agents if item.get("status") == "active"]
    if len(active_agents) != EXPECTED_AGENT_COUNT:
        raise GenerationError(
            f"expected {EXPECTED_AGENT_COUNT} active agents, found {len(active_agents)}"
        )
    agent_ids = [str(item.get("agent_id", "")) for item in active_agents]
    if len(set(agent_ids)) != EXPECTED_AGENT_COUNT or "" in agent_ids:
        raise GenerationError("active agent registry contains duplicate or empty agent ids")
    for agent in active_agents:
        source = str(agent.get("canonical_file", ""))
        if not (addon_root / source).is_file():
            raise GenerationError(f"registered agent is missing: {source}")

    reconciled_commands = list(commands)
    browser_entries = [
        item for item in reconciled_commands if item.get("canonical_file") == SKILL_BROWSER_PATH
    ]
    if len(browser_entries) > 1:
        raise GenerationError("command registry contains duplicate skill-browser entries")
    if not browser_entries:
        browser_skill = next(
            (item for item in active_skills if item.get("path") == SKILL_BROWSER_PATH), None
        )
        if browser_skill is None:
            raise GenerationError("cannot reconcile skill-browser: active skill is missing")
        reconciled_commands.append(
            {
                "slug": "skill-browser",
                "description": browser_skill.get(
                    "description", "Browse and search the PMOS skill catalog"
                ),
                "type": "core",
                "owner_plugin": "core",
                "canonical_file": SKILL_BROWSER_PATH,
                "argument_hint": "[search terms]",
                "writes_files": False,
                "requires_confirmation": False,
                "uses_memory": "none",
                "setup_required": False,
            }
        )

    if len(reconciled_commands) != EXPECTED_COMMAND_COUNT:
        raise GenerationError(
            f"expected {EXPECTED_COMMAND_COUNT} reconciled commands, "
            f"found {len(reconciled_commands)}"
        )
    command_paths = [str(item.get("canonical_file", "")) for item in reconciled_commands]
    if len(set(command_paths)) != EXPECTED_COMMAND_COUNT:
        raise GenerationError("reconciled command set contains duplicate canonical skills")
    if not set(command_paths).issubset(skill_paths):
        missing = sorted(set(command_paths) - skill_paths)
        raise GenerationError(f"commands reference inactive or unknown skills: {missing}")

    generated_slugs = [adapter_slug(item) for item in reconciled_commands]
    if len(set(generated_slugs)) != EXPECTED_COMMAND_COUNT:
        raise GenerationError("Codex command names collide after PMOS namespacing")

    servers = mcp.get("mcpServers") if isinstance(mcp, dict) else None
    if not isinstance(servers, dict):
        raise GenerationError(f"{ADDON_ROOT_REL}/.mcp.json must contain mcpServers")
    if tuple(servers.keys()) != EXPECTED_MCP_NAMES:
        raise GenerationError(
            "MCP server set or order changed; review before regenerating: "
            + ", ".join(servers.keys())
        )

    return (
        sorted(active_agents, key=lambda item: str(item["agent_id"])),
        sorted(reconciled_commands, key=adapter_slug),
        servers,
    )


def render_agent(root: Path, agent: dict[str, Any]) -> str:
    source_path = root / ADDON_ROOT_REL / str(agent["canonical_file"])
    metadata, source_body = parse_markdown_frontmatter(source_path)
    agent_id = str(agent["agent_id"])
    source_description = str(metadata.get("description") or agent_id)
    description = translate_host_assumptions(f"PMOS {source_description}")
    body = qualify_addon_paths(translate_host_assumptions(source_body))
    readonly = bool(agent.get("readonly")) or not bool(agent.get("writes_allowed"))
    posture = (
        "This is a read-only PMOS agent. Do not create, edit, move, or delete files."
        if readonly
        else "Write only workflow outputs explicitly authorized by the user, and preserve all unrelated files."
    )
    preface = (
        "# Codex adapter contract\n\n"
        "Run as the PMOS specialist named by this file. Use native Codex file, web, MCP, "
        "skill, and subagent capabilities. Treat exact host tool labels or legacy slash "
        "commands found in referenced source material as capability descriptions, not literal "
        f"runtime dependencies. Resolve add-on resources under `{ADDON_ROOT_REL}/` and "
        "workspace Context paths from the workspace root. "
        f"{posture}\n\n"
    )
    instructions = preface + body
    sandbox_mode = "read-only" if readonly else "workspace-write"
    rendered = (
        f"# {AGENT_MARKER}\n"
        f"name = {toml_string(agent_id)}\n"
        f"description = {toml_string(description)}\n"
        f"sandbox_mode = {toml_string(sandbox_mode)}\n"
        f"developer_instructions = {toml_string(instructions)}\n"
    )
    try:
        parsed = tomllib.loads(rendered)
    except tomllib.TOMLDecodeError as exc:
        raise GenerationError(f"generated invalid agent TOML for {agent_id}: {exc}") from exc
    required = {"name", "description", "developer_instructions"}
    if not required.issubset(parsed):
        raise GenerationError(f"generated agent {agent_id} lacks required Codex fields")
    return rendered


def render_command(command: dict[str, Any]) -> str:
    slug = adapter_slug(command)
    source = f"{ADDON_ROOT_REL}/{command['canonical_file']}"
    description = translate_host_assumptions(str(command.get("description", "PMOS command")))
    argument_hint = str(command.get("argument_hint", "")).strip()
    writes = bool(command.get("writes_files"))
    confirm = bool(command.get("requires_confirmation"))
    setup = bool(command.get("setup_required"))

    frontmatter = ["---", f"description: {json.dumps('PMOS: ' + description, ensure_ascii=False)}"]
    if argument_hint:
        frontmatter.append(
            f"argument-hint: {json.dumps(argument_hint, ensure_ascii=False)}"
        )
    frontmatter.append("---")

    policy = [
        "Read the canonical skill named below before acting; it remains the source of truth.",
        "Use the arguments supplied with this invocation as `$ARGUMENTS` and preserve their order.",
        "Map exact host tool labels in the canonical skill to the equivalent native Codex capability.",
        "Map legacy slash-command references to the corresponding `$pm-os-*` adapter or skill.",
        "Use native structured user input when available; otherwise ask one concise inline question.",
    ]
    if setup:
        policy.append("Verify the PMOS Context and project prerequisites before execution.")
    if writes:
        policy.append("Keep every write inside the canonical PMOS destination described by the skill.")
    if confirm:
        policy.append("Obtain the skill's required explicit confirmation before writes or external actions.")
    else:
        policy.append("Do not introduce a new confirmation gate unless the requested action requires one.")

    body = "\n".join(f"{index}. {line}" for index, line in enumerate(policy, 1))
    return (
        "\n".join(frontmatter)
        + f"\n<!-- {MARKER} -->\n\n"
        + f"# PMOS adapter: ${slug}\n\n"
        + f"Canonical skill: `{source}`\n\n"
        + body
        + "\n"
    )


SESSION_START_SCRIPT = r'''#!/usr/bin/env python3
# Generated by bin/generate-codex-adapters.py; do not edit.
"""Sequential PMOS SessionStart adapter: tidy wins over daily drip."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from typing import Any


FALLBACK_ROOT = Path(__file__).resolve().parents[3]


def read_payload() -> dict[str, Any]:
    try:
        value = json.load(sys.stdin)
    except (json.JSONDecodeError, OSError):
        return {}
    return value if isinstance(value, dict) else {}


def find_project_root(cwd: object) -> Path:
    candidates: list[Path] = []
    if isinstance(cwd, str) and cwd:
        candidate = Path(cwd).expanduser().resolve()
        candidates.extend((candidate, *candidate.parents))
    candidates.append(FALLBACK_ROOT)
    for candidate in candidates:
        if (
            (candidate / ".aiwg/addons/pm-os/hooks/tidy-reminder.sh").is_file()
            and (candidate / ".aiwg/addons/pm-os/hooks/drip-reminder.sh").is_file()
        ):
            return candidate
    return FALLBACK_ROOT


def extract_context(stdout: str) -> str:
    for raw_line in reversed(stdout.splitlines()):
        line = raw_line.strip()
        if not line:
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(value, dict):
            continue
        direct = value.get("additional_context") or value.get("additionalContext")
        if isinstance(direct, str) and direct.strip():
            return direct.strip()
        specific = value.get("hookSpecificOutput")
        if isinstance(specific, dict):
            nested = specific.get("additionalContext")
            if isinstance(nested, str) and nested.strip():
                return nested.strip()
    return ""


def translate_context(context: str) -> str:
    return context.replace("/daily-drip", "$pm-os-daily-drip").replace(
        "/tidy", "$pm-os-tidy"
    )


def run_reminder(root: Path, filename: str) -> str:
    script = root / ".aiwg/addons/pm-os/hooks" / filename
    try:
        result = subprocess.run(
            ["/bin/bash", str(script)],
            cwd=root,
            text=True,
            capture_output=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    if result.returncode != 0:
        return ""
    return translate_context(extract_context(result.stdout))


def main() -> int:
    payload = read_payload()
    event = payload.get("hook_event_name")
    if event not in {None, "SessionStart"}:
        return 0
    root = find_project_root(payload.get("cwd"))

    # One handler owns both checks so Codex never starts them concurrently.
    context = run_reminder(root, "tidy-reminder.sh")
    if not context:
        context = run_reminder(root, "drip-reminder.sh")
    if not context:
        return 0

    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "SessionStart",
                    "additionalContext": context,
                }
            },
            ensure_ascii=False,
            separators=(",", ":"),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


SAVE_GUARD_SCRIPT = r'''#!/usr/bin/env python3
# Generated by bin/generate-codex-adapters.py; do not edit.
"""Codex PreToolUse save guard for validated apply_patch Add File headers."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path
from typing import Any


FALLBACK_ROOT = Path(__file__).resolve().parents[3]
ADD_PREFIX = "*** Add File: "


def read_payload() -> dict[str, Any]:
    try:
        value = json.load(sys.stdin)
    except (json.JSONDecodeError, OSError):
        return {}
    return value if isinstance(value, dict) else {}


def find_project_root(cwd: object) -> Path:
    candidates: list[Path] = []
    if isinstance(cwd, str) and cwd:
        candidate = Path(cwd).expanduser().resolve()
        candidates.extend((candidate, *candidate.parents))
    candidates.append(FALLBACK_ROOT)
    for candidate in candidates:
        if (
            candidate / ".aiwg/addons/pm-os/bin/memory/relocate-into-canonical.sh"
        ).is_file():
            return candidate
    return FALLBACK_ROOT


def engine_redirect(root: Path, source: str) -> Path | None:
    engine = root / ".aiwg/addons/pm-os/bin/memory/relocate-into-canonical.sh"
    try:
        result = subprocess.run(
            [
                "/bin/bash",
                str(engine),
                "--root",
                str(root),
                "--path",
                source,
                "--compute",
                "--json",
            ],
            cwd=root,
            text=True,
            capture_output=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    try:
        value = json.loads(result.stdout.strip().splitlines()[-1])
    except (IndexError, json.JSONDecodeError):
        return None
    if not isinstance(value, dict) or value.get("status") != "redirect":
        return None
    target = value.get("to")
    return Path(target) if isinstance(target, str) and target else None


def safe_relative_target(root: Path, source: str, target: Path) -> tuple[str, Path] | None:
    if not source or source != source.strip() or any(char in source for char in "\r\n\t"):
        return None
    if target.suffix != ".md" or target.name != Path(source).name:
        return None

    work = (root / "📂 Context/Work").resolve()
    try:
        resolved_target = target.resolve(strict=False)
        relative_to_work = resolved_target.relative_to(work)
        relative_to_root = resolved_target.relative_to(root.resolve())
    except (OSError, ValueError):
        return None
    if not relative_to_work.parts or relative_to_work.parts[0] == "..":
        return None
    if resolved_target.exists() or resolved_target.is_symlink():
        return None

    probe = work
    for part in relative_to_work.parent.parts:
        probe = probe / part
        if probe.is_symlink():
            return None
    return relative_to_root.as_posix(), resolved_target


def preserve_newline(original: str, replacement: str) -> str:
    if original.endswith("\r\n"):
        return replacement + "\r\n"
    if original.endswith("\n"):
        return replacement + "\n"
    return replacement


def rewrite_add_headers(root: Path, command: str) -> tuple[str, list[tuple[str, str]]]:
    lines = command.splitlines(keepends=True)
    original_headers: set[str] = set()
    candidates: list[tuple[int, str, str, Path]] = []

    for index, line in enumerate(lines):
        header = line.rstrip("\r\n")
        if not header.startswith(ADD_PREFIX):
            continue
        source = header[len(ADD_PREFIX) :]
        original_headers.add(source.removeprefix("./"))
        target = engine_redirect(root, source)
        if target is None:
            continue
        validated = safe_relative_target(root, source, target)
        if validated is None:
            continue
        relative, absolute = validated
        candidates.append((index, source, relative, absolute))

    if not candidates:
        return command, []

    targets = [item[2] for item in candidates]
    if len(set(targets)) != len(targets):
        return command, []
    for _, source, target, _ in candidates:
        if target in original_headers and target != source.removeprefix("./"):
            return command, []

    applied: list[tuple[str, str]] = []
    for index, source, relative, absolute in candidates:
        try:
            absolute.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
            absolute.parent.resolve().relative_to((root / "📂 Context/Work").resolve())
        except (OSError, ValueError):
            continue
        if absolute.exists() or absolute.is_symlink():
            continue
        lines[index] = preserve_newline(lines[index], ADD_PREFIX + relative)
        applied.append((source, relative))

    return "".join(lines), applied


def main() -> int:
    payload = read_payload()
    if payload.get("tool_name") != "apply_patch":
        return 0
    if payload.get("hook_event_name") not in {None, "PreToolUse"}:
        return 0
    tool_input = payload.get("tool_input")
    if not isinstance(tool_input, dict):
        return 0
    command = tool_input.get("command")
    if not isinstance(command, str) or not command:
        return 0

    root = find_project_root(payload.get("cwd"))
    rewritten, mappings = rewrite_add_headers(root, command)
    if not mappings or rewritten == command:
        return 0

    updated_input = dict(tool_input)
    updated_input["command"] = rewritten
    summary = "; ".join(f"{source} -> {target}" for source, target in mappings)
    message = f"[PMOS SAVE GUARD] Redirected new document path(s): {summary}"
    print(
        json.dumps(
            {
                "hookSpecificOutput": {
                    "hookEventName": "PreToolUse",
                    "permissionDecision": "allow",
                    "permissionDecisionReason": "Validated PMOS canonical-path rewrite.",
                    "updatedInput": updated_input,
                    "additionalContext": message,
                }
            },
            ensure_ascii=False,
            separators=(",", ":"),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


