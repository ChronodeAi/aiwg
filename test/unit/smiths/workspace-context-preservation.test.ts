// Protect operator documentation during workspace audit, migration and doctor.
import { afterEach, beforeEach, expect, it } from 'vitest';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { auditWorkspaceContext, diagnoseWorkspaceContext, migrateWorkspaceContext } from '../../../src/smiths/context-pipeline/workspace-context.js';
import { isGeneratedRootContext, replaceBlock, stripGeneratedBlocks, PROVIDER_BOOTSTRAP_START, PROVIDER_BOOTSTRAP_END } from '../../../src/smiths/context-pipeline/workspace-context-shared.js';
import { listProviderDefinitions } from '../../../src/providers/provider-definitions.js';

let root: string;
beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'aiwg-preserve-context-'));
  await mkdir(join(root, '.aiwg'));
  await writeFile(join(root, '.aiwg/aiwg.config'), JSON.stringify({ version: '1', providers: ['codex'], installed: {}, scripts: {} }));
});
afterEach(async () => { await rm(root, { recursive: true, force: true }); });

it('recognizes generated signatures only as head metadata', async () => {
  const prose = '# Operator startup\n' + 'Preserve this project convention.\n'.repeat(13) + 'Here is a literal signature: <!-- aiwg-managed -->\n';
  expect(isGeneratedRootContext('AGENTS.md', prose)).toBe(false);
  expect(isGeneratedRootContext('AGENTS.md', '# Startup\n<!-- aiwg-managed -->\n')).toBe(true);
  await writeFile(join(root, 'AGENTS.md'), prose);
  const audit = await auditWorkspaceContext(root);
  expect(audit.sources.find(s => s.path === 'AGENTS.md')?.operatorContent).toBe(prose.trim());
  await migrateWorkspaceContext(root, { apply: true, includeGeneratedContext: true });
  expect(await readFile(join(root, 'WORKSPACE.md'), 'utf8')).toContain(prose.trim());
});

it.each([PROVIDER_BOOTSTRAP_START, PROVIDER_BOOTSTRAP_END])('treats a lone managed marker as prose: %s', async marker => {
  const prose = '# Startup documentation\nOne marker is illustrative:\n' + marker + '\nKeep the surrounding convention.\n';
  expect(replaceBlock(prose, PROVIDER_BOOTSTRAP_START, PROVIDER_BOOTSTRAP_END, 'replacement')).toBeNull();
  expect(stripGeneratedBlocks(prose)).toBe(prose.trim());
  await writeFile(join(root, 'AGENTS.md'), prose);
  expect((await auditWorkspaceContext(root)).sources.find(s => s.path === 'AGENTS.md')?.operatorContent).toBe(prose.trim());
  await expect(diagnoseWorkspaceContext(root)).resolves.toBeDefined();
  await migrateWorkspaceContext(root, { apply: true, includeGeneratedContext: true });
  expect(await readFile(join(root, 'WORKSPACE.md'), 'utf8')).toContain(prose.trim());
});

const registered = listProviderDefinitions().filter(d => d.context.configRegistration);
it.each(registered)('doctor requires both registered context files for $id', async definition => {
  await writeFile(join(root, '.aiwg/aiwg.config'), JSON.stringify({ version: '1', providers: [definition.id], installed: {}, scripts: {} }));
  await migrateWorkspaceContext(root, { apply: true, includeGeneratedContext: true });
  const { file, key } = definition.context.configRegistration!;
  const configPath = join(root, file);
  const config = JSON.parse(await readFile(configPath, 'utf8'));
  expect(config[key]).toEqual(expect.arrayContaining(['WORKSPACE.md', 'AIWG.md']));
  for (const missing of ['AIWG.md', 'WORKSPACE.md']) {
    await writeFile(configPath, JSON.stringify({ ...config, [key]: config[key].filter((v: string) => v !== missing) }));
    expect(await diagnoseWorkspaceContext(root)).toEqual(expect.arrayContaining([expect.objectContaining({ code: 'registration-drift', path: file, message: expect.stringContaining(missing) })]));
  }
  await writeFile(configPath, JSON.stringify(config));
  expect((await diagnoseWorkspaceContext(root)).filter(d => d.code === 'registration-drift')).toEqual([]);
});

it('preserves standalone generated-comment quotations in the operator body', async () => {
  const prose = '# Operator startup\n' + 'Keep the project convention.\n'.repeat(13)
    + '<!-- aiwg-managed -->\n<!-- Generated by AIWG for illustration only -->\n';
  expect(stripGeneratedBlocks(prose)).toBe(prose.trim());
  await writeFile(join(root, 'AGENTS.md'), prose);
  expect((await auditWorkspaceContext(root)).sources.find(s => s.path === 'AGENTS.md')?.operatorContent).toBe(prose.trim());
  await migrateWorkspaceContext(root, { apply: true, includeGeneratedContext: true });
  expect(await readFile(join(root, 'WORKSPACE.md'), 'utf8')).toContain(prose.trim());
});
